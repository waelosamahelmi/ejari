/**
 * Demo seeder (§15). Generates `supabase/seed.sql` from the deterministic demo
 * dataset (src/demo/demo-data.ts) and, with `--apply`, executes it against
 * DATABASE_URL. `supabase db reset` also loads the generated seed.sql.
 *
 *   pnpm seed            → regenerate seed.sql and apply it (truncates demo tables!)
 *   pnpm seed --no-apply → only regenerate seed.sql
 */
