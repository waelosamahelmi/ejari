type Val = string | number | boolean | null | undefined | readonly string[] | Record<string, unknown> | unknown[];

function lit(v: Val): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "string") return `'${v.replace(/'/g, "''")}'`;
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) {
    return `array[${(v as string[]).map(lit).join(",")}]::text[]`;
  }
  return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
}

function insert(table: string, rows: Record<string, Val>[]): string {
  if (rows.length === 0) return "";
  const cols = Object.keys(rows[0]!);
  const chunks: string[] = [];
  for (let i = 0; i < rows.length; i += 500) {
    const values = rows
      .slice(i, i + 500)
      .map((r) => `(${cols.map((c) => lit(r[c])).join(", ")})`)
      .join(",\n  ");
    chunks.push(`insert into public.${table} (${cols.join(", ")}) values\n  ${values};`);
  }
  return chunks.join("\n");
}

export const SYSTEM_TEMPLATE_IDS = {
  residential: "2d000000-0000-4000-8000-000000000001",
  investment: "2d000000-0000-4000-8000-000000000002",
} as const;

function templateRows(tpl: ContractTemplate, id: string) {
  return {
    template: {
      id,
      org_id: null,
      type: tpl.type,
      name: tpl.name,
      version: 1,
      family_id: id,
      preamble: tpl.preamble,
      closing: tpl.closing ?? null,
      is_default: true,
    },
    clauses: tpl.clauses.map((c) => ({
      org_id: null,
      template_id: id,
      position: c.position,
      key: c.key,
      body: c.body,
      condition: c.condition ?? null,
      default_condition: c.defaultCondition ?? null,
      optional: c.optional ?? false,
      default_enabled: c.defaultEnabled ?? true,
    })),
  };
}

